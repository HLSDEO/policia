-- ===================================================================================================================
-- SMS/MMS: contatos, conversas, mensagens e anexos
--
-- Tabelas: SMS_TB01_CONTATOS, SMS_TB02_CONVERSAS, SMS_TB03_PARTICIPANTES, SMS_TB04_MENSAGENS,
--          SMS_TB05_ANEXOS
-- ===================================================================================================================

-- PUBLIC no fim do search_path: e onde ficam pg_trgm, fuzzystrmatch e pgcrypto —
-- sem ele, gin_trgm_ops e crypt()/gen_salt() nao sao encontrados sem qualificar.
SET search_path TO INVESTIGACAO, PUBLIC;

-- =====================================================================
-- SMS — mesmo formato de Chat/InstantMessage do WhatsApp (WPP_TB0x), só que
-- com Source = "Native Messages" em vez de "WhatsApp". Tabelas espelhadas
-- para manter o nome fiel à origem dos dados.
-- =====================================================================
CREATE TABLE SMS_TB01_CONTATOS (
    ID_CONTATO              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_EXTRACAO             BIGINT NOT NULL,
    NU_TELEFONE             TEXT NOT NULL,
    NO_CONTATO              TEXT,
    IN_DONO_DISPOSITIVO     BOOLEAN,
    ID_PESSOA_ASSOCIADA     BIGINT,
    ID_MUNICIPIO_ASSOCIADO  INTEGER,
    ID_UF_ASSOCIADA         SMALLINT,
    ID_USUARIO_ASSOCIOU     BIGINT,
    CONSTRAINT FK50_SMS_TB01_INQ_TB02 FOREIGN KEY (ID_EXTRACAO)
        REFERENCES INQ_TB02_EXTRACOES (ID_EXTRACAO),
    CONSTRAINT UQ02_SMS_TB01_EXTRACAO_TEL UNIQUE (ID_EXTRACAO, NU_TELEFONE),
    CONSTRAINT FK62_SMS_TB01_PES_TB01 FOREIGN KEY (ID_PESSOA_ASSOCIADA)
        REFERENCES DADOS_EXTRAIDOS.PES_TB01_PESSOAS (ID_PESSOA),
    CONSTRAINT FK63_SMS_TB01_IBGE_TB08 FOREIGN KEY (ID_MUNICIPIO_ASSOCIADO)
        REFERENCES DADOS_REFERENCIA.IBGE_TB08_MUNICIPIO (ID_MUNICIPIO),
    CONSTRAINT FK64_SMS_TB01_IBGE_TB03 FOREIGN KEY (ID_UF_ASSOCIADA)
        REFERENCES DADOS_REFERENCIA.IBGE_TB03_UF (ID_UF),
    CONSTRAINT FK72_SMS_TB01_USR_TB01 FOREIGN KEY (ID_USUARIO_ASSOCIOU)
        REFERENCES SEGURANCA.USR_TB01_USUARIOS (ID_USUARIO)
);

CREATE TABLE SMS_TB02_CONVERSAS (
    ID_CONVERSA          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_EXTRACAO          BIGINT NOT NULL,
    NO_GRUPO             TEXT,  -- paridade com WPP_TB02 (SMS/MMS normalmente não tem, fica nulo)
    TP_CONVERSA          VARCHAR(3000) NOT NULL,
    DT_INICIO            TIMESTAMP,
    DT_ULTIMA_ATIVIDADE  TIMESTAMP,
    CD_STATUS_UFDR       VARCHAR(50),
    TP_CHAT_UFDR         VARCHAR(50),
    TX_DESCRICAO         TEXT,
    NO_CONTA             VARCHAR(3000),
    TX_STATUS_CHAT       VARCHAR(3000),
    CONSTRAINT FK51_SMS_TB02_INQ_TB02 FOREIGN KEY (ID_EXTRACAO)
        REFERENCES INQ_TB02_EXTRACOES (ID_EXTRACAO)
);

CREATE TABLE SMS_TB03_PARTICIPANTES (
    ID_CONVERSA  BIGINT NOT NULL,
    ID_CONTATO   BIGINT NOT NULL,
    PRIMARY KEY (ID_CONVERSA, ID_CONTATO),
    CONSTRAINT FK52_SMS_TB03_SMS_TB02 FOREIGN KEY (ID_CONVERSA)
        REFERENCES SMS_TB02_CONVERSAS (ID_CONVERSA),
    CONSTRAINT FK53_SMS_TB03_SMS_TB01 FOREIGN KEY (ID_CONTATO)
        REFERENCES SMS_TB01_CONTATOS (ID_CONTATO)
);

CREATE INDEX IF NOT EXISTS IX153_SMS_TB03_ID_CONTATO ON SMS_TB03_PARTICIPANTES (ID_CONTATO);

CREATE TABLE SMS_TB04_MENSAGENS (
    ID_MENSAGEM                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CONVERSA                BIGINT NOT NULL,
    ID_CONTATO_REMETENTE       BIGINT,
    TX_MENSAGEM                TEXT,
    DT_MENSAGEM                TIMESTAMP,
    TP_MENSAGEM                VARCHAR(3000),  -- Type (Sms/Mms)
    CD_STATUS_MENSAGEM         VARCHAR(3000),
    NO_PASTA                   VARCHAR(3000),  -- Folder: Inbox/Sent/...
    IN_ENVIADA                 BOOLEAN,
    NU_IDENTIFICADOR_ORIGINAL  TEXT,
    VL_LATITUDE                NUMERIC(10,6),
    VL_LONGITUDE               NUMERIC(10,6),
    CD_STATUS_UFDR             VARCHAR(50),
    IN_ENCAMINHADA             BOOLEAN,
    IN_APAGADA_REMETENTE       BOOLEAN,
    IN_TEMPORARIA              BOOLEAN,
    IN_EDITADA                 BOOLEAN,
    TX_ROTULOS                 VARCHAR(3000),
    NU_IDENT_CITADO            VARCHAR(3000),
    TX_DESTINATARIOS           TEXT,
    TX_ASSUNTO                 TEXT,
    TX_MOTIVO_EXCLUSAO         VARCHAR(3000),
    NU_SMSC                    VARCHAR(3000),
    DT_ENTREGUE                TIMESTAMP,
    DT_LIDA                    TIMESTAMP,
    DT_REPRODUZIDA             TIMESTAMP,
    CONSTRAINT FK54_SMS_TB04_SMS_TB02 FOREIGN KEY (ID_CONVERSA)
        REFERENCES SMS_TB02_CONVERSAS (ID_CONVERSA),
    CONSTRAINT FK55_SMS_TB04_SMS_TB01 FOREIGN KEY (ID_CONTATO_REMETENTE)
        REFERENCES SMS_TB01_CONTATOS (ID_CONTATO)
);

CREATE INDEX IX22_SMS_TB04_ID_CONVERSA     ON SMS_TB04_MENSAGENS (ID_CONVERSA);
CREATE INDEX IX63_SMS_TB04_CONVERSA_MSG ON SMS_TB04_MENSAGENS (ID_CONVERSA, ID_MENSAGEM);
CREATE INDEX IF NOT EXISTS IX149_SMS_TB04_CONTATO_REMETENTE ON SMS_TB04_MENSAGENS (ID_CONTATO_REMETENTE);
CREATE INDEX IF NOT EXISTS IX148_SMS_TB04_APAGADA ON SMS_TB04_MENSAGENS (ID_CONVERSA)
    WHERE CD_STATUS_UFDR IS NOT NULL AND CD_STATUS_UFDR <> 'Intact';
CREATE INDEX IF NOT EXISTS IX187_SMS_TB04_TX_MENSAGEM_TRGM
    ON SMS_TB04_MENSAGENS USING gin (TX_MENSAGEM gin_trgm_ops);
CREATE INDEX IF NOT EXISTS IX206_SMS_TB04_IDENT_ORIGINAL
    ON SMS_TB04_MENSAGENS (NU_IDENTIFICADOR_ORIGINAL)
    WHERE NU_IDENTIFICADOR_ORIGINAL IS NOT NULL;

CREATE TABLE SMS_TB05_ANEXOS (
    ID_ANEXO         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_MENSAGEM      BIGINT NOT NULL,
    NO_ARQUIVO       TEXT,
    TP_CONTEUDO      TEXT,
    QT_BYTES         BIGINT,
    CO_CAMINHO_ZIP   TEXT,
    TX_TRANSCRICAO   TEXT,
    TX_TITULO        TEXT,
    CO_URL_ORIGINAL  TEXT,
    CO_FILE_ID       VARCHAR(80),
    CONSTRAINT FK56_SMS_TB05_SMS_TB04 FOREIGN KEY (ID_MENSAGEM)
        REFERENCES SMS_TB04_MENSAGENS (ID_MENSAGEM)
);

CREATE INDEX IX66_SMS_TB05_ID_MENSAGEM ON SMS_TB05_ANEXOS (ID_MENSAGEM);
CREATE INDEX IX80_SMS_TB05_CAMINHO_ZIP ON SMS_TB05_ANEXOS (CO_CAMINHO_ZIP);
CREATE INDEX IF NOT EXISTS IX154_SMS_TB05_FILE_ID ON SMS_TB05_ANEXOS (CO_FILE_ID) WHERE CO_FILE_ID IS NOT NULL;
CREATE INDEX IF NOT EXISTS IX190_SMS_TB05_TX_TRANSCRICAO_TRGM
    ON SMS_TB05_ANEXOS USING gin (TX_TRANSCRICAO gin_trgm_ops);

RESET search_path;
