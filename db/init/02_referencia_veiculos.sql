-- Tabelas de dominio do Detran (marca, modelo, cor, ...)
--
-- Tabelas: VEI_TB01_MARCA, VEI_TB02_SEGMENTO, VEI_TB03_SUB_SEGMENTO, VEI_TB04_GRUPO_MODELO, VEI_TB05_MODELO,
--          VEI_TB06_MUNICIPIO, VEI_TB07_COMBUSTIVEL, VEI_TB08_COR, VEI_TB09_CARROCERIA,
--          VEI_TB10_ESPECIE_VEICULO, VEI_TB11_TIPO_VEICULO, VEI_TB12_NACIONALIDADE, VEI_TB13_REGIAO,
--          VEI_TB14_RESTRICAO, VEI_TB15_TIPO_PESSOA
-- ===================================================================================================================

-- PUBLIC no fim do search_path: e onde ficam pg_trgm, fuzzystrmatch e pgcrypto —
-- sem ele, gin_trgm_ops e crypt()/gen_salt() nao sao encontrados sem qualificar.
SET search_path TO DADOS_REFERENCIA, PUBLIC;

-- 01 · marca.csv
CREATE TABLE VEI_TB01_MARCA (
    ID_MARCA  INTEGER PRIMARY KEY,
    NO_MARCA  VARCHAR(120) NOT NULL
);

-- 02 · segmento_veiculo.csv
CREATE TABLE VEI_TB02_SEGMENTO (
    ID_SEGMENTO  INTEGER PRIMARY KEY,
    NO_SEGMENTO  VARCHAR(60) NOT NULL
);

-- 03 · sub_segmento_veiculo.csv
CREATE TABLE VEI_TB03_SUB_SEGMENTO (
    ID_SUB_SEGMENTO  INTEGER PRIMARY KEY,
    ID_SEGMENTO      INTEGER NOT NULL,
    NO_SUB_SEGMENTO  VARCHAR(60) NOT NULL,
    CONSTRAINT FK01_VEI_TB03_VEI_TB02 FOREIGN KEY (ID_SEGMENTO)
        REFERENCES VEI_TB02_SEGMENTO (ID_SEGMENTO)
);

-- 04 · grupo_modelo.csv
CREATE TABLE VEI_TB04_GRUPO_MODELO (
    ID_GRUPO_MODELO  INTEGER PRIMARY KEY,
    NO_GRUPO_MODELO  VARCHAR(120) NOT NULL,
    VL_MEDIA_PRECO   NUMERIC(15,2),
    NU_VERSION       VARCHAR(30)
);

-- 05 · modelo.csv
CREATE TABLE VEI_TB05_MODELO (
    ID_MODELO        INTEGER PRIMARY KEY,
    NO_MODELO        VARCHAR(200),  -- 2 registros vêm com nome em branco no vazamento
    ID_MARCA         INTEGER NOT NULL,
    ID_SEGMENTO      INTEGER NOT NULL,
    ID_SUB_SEGMENTO  INTEGER NOT NULL,
    ID_GRUPO_MODELO  INTEGER NOT NULL,
    VL_MEDIA_PRECO   NUMERIC(15,2),
    NU_VERSION       VARCHAR(30),
    CONSTRAINT FK02_VEI_TB05_VEI_TB01 FOREIGN KEY (ID_MARCA)
        REFERENCES VEI_TB01_MARCA (ID_MARCA),
    CONSTRAINT FK03_VEI_TB05_VEI_TB02 FOREIGN KEY (ID_SEGMENTO)
        REFERENCES VEI_TB02_SEGMENTO (ID_SEGMENTO),
    CONSTRAINT FK04_VEI_TB05_VEI_TB03 FOREIGN KEY (ID_SUB_SEGMENTO)
        REFERENCES VEI_TB03_SUB_SEGMENTO (ID_SUB_SEGMENTO),
    CONSTRAINT FK05_VEI_TB05_VEI_TB04 FOREIGN KEY (ID_GRUPO_MODELO)
        REFERENCES VEI_TB04_GRUPO_MODELO (ID_GRUPO_MODELO)
);

CREATE INDEX IX01_VEI_TB05_ID_MARCA        ON VEI_TB05_MODELO (ID_MARCA);
CREATE INDEX IX02_VEI_TB05_ID_GRUPO_MODELO ON VEI_TB05_MODELO (ID_GRUPO_MODELO);

-- 06 · municipio.csv
CREATE TABLE VEI_TB06_MUNICIPIO (
    ID_MUNICIPIO  INTEGER PRIMARY KEY,
    NO_MUNICIPIO  VARCHAR(120) NOT NULL,
    SG_UF         CHAR(2)
);

CREATE INDEX IX03_VEI_TB06_SG_UF           ON VEI_TB06_MUNICIPIO (SG_UF);

-- 07 · combustivel.csv
CREATE TABLE VEI_TB07_COMBUSTIVEL (
    ID_COMBUSTIVEL  SMALLINT PRIMARY KEY,
    NO_COMBUSTIVEL  VARCHAR(60) NOT NULL
);

-- 08 · cor.csv
CREATE TABLE VEI_TB08_COR (
    ID_COR  SMALLINT PRIMARY KEY,
    NO_COR  VARCHAR(40) NOT NULL
);

-- 09 · carroceria.csv
CREATE TABLE VEI_TB09_CARROCERIA (
    ID_CARROCERIA  INTEGER PRIMARY KEY,
    NO_CARROCERIA  VARCHAR(80) NOT NULL
);

-- 10 · especie_veiculo.csv
CREATE TABLE VEI_TB10_ESPECIE_VEICULO (
    ID_ESPECIE_VEICULO  SMALLINT PRIMARY KEY,
    NO_ESPECIE_VEICULO  VARCHAR(40) NOT NULL
);

-- 11 · tipo_veiculo.csv
CREATE TABLE VEI_TB11_TIPO_VEICULO (
    ID_TIPO_VEICULO  SMALLINT PRIMARY KEY,
    NO_TIPO_VEICULO  VARCHAR(60) NOT NULL
);

-- 12 · nacionalidade.csv
CREATE TABLE VEI_TB12_NACIONALIDADE (
    ID_NACIONALIDADE  SMALLINT PRIMARY KEY,
    NO_NACIONALIDADE  VARCHAR(40) NOT NULL
);

-- 13 · regiao.csv
CREATE TABLE VEI_TB13_REGIAO (
    ID_REGIAO  SMALLINT PRIMARY KEY,
    NO_REGIAO  VARCHAR(60) NOT NULL
);

-- 14 · restricoes.csv
CREATE TABLE VEI_TB14_RESTRICAO (
    ID_RESTRICAO  SMALLINT PRIMARY KEY,
    NO_RESTRICAO  VARCHAR(60) NOT NULL
);

-- 15 · tipo_pessoa.csv
CREATE TABLE VEI_TB15_TIPO_PESSOA (
    ID_TIPO_PESSOA  SMALLINT PRIMARY KEY,
    NO_TIPO_PESSOA  VARCHAR(40) NOT NULL
);

RESET search_path;
