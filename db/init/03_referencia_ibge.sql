-- ===================================================================================================================
-- Divisao territorial do IBGE (pais -> subdistrito)
--
-- Tabelas: IBGE_TB01_PAIS, IBGE_TB02_REGIAO, IBGE_TB03_UF, IBGE_TB04_MESORREGIAO, IBGE_TB05_MICRORREGIAO,
--          IBGE_TB06_REGIAO_INTERMEDIARIA, IBGE_TB07_REGIAO_IMEDIATA, IBGE_TB08_MUNICIPIO,
--          IBGE_TB09_DISTRITO, IBGE_TB10_SUBDISTRITO
-- ===================================================================================================================

-- PUBLIC no fim do search_path: e onde ficam pg_trgm, fuzzystrmatch e pgcrypto —
-- sem ele, gin_trgm_ops e crypt()/gen_salt() nao sao encontrados sem qualificar.
SET search_path TO DADOS_REFERENCIA, PUBLIC;

-- 01 · paises.json — catálogo mundial de países, independente da hierarquia BR abaixo
CREATE TABLE IBGE_TB01_PAIS (
    CD_PAIS_M49            INTEGER PRIMARY KEY,
    SG_PAIS                CHAR(2),
    SG_PAIS_ALPHA3         CHAR(3),
    NO_PAIS                VARCHAR(120) NOT NULL,
    NO_PAIS_EN             VARCHAR(120),
    QT_AREA_KM2            NUMERIC(15,2),
    NO_REGIAO_MUNDIAL      VARCHAR(60),
    NO_SUB_REGIAO_MUNDIAL  VARCHAR(80),
    NO_CAPITAL             VARCHAR(120),
    TX_HISTORICO           TEXT
);

-- 02 · localidades/regioes.json
CREATE TABLE IBGE_TB02_REGIAO (
    ID_REGIAO  SMALLINT PRIMARY KEY,
    SG_REGIAO  CHAR(2) NOT NULL,
    NO_REGIAO  VARCHAR(20) NOT NULL
);

-- 03 · localidades/estados.json
CREATE TABLE IBGE_TB03_UF (
    ID_UF      SMALLINT PRIMARY KEY,
    SG_UF      CHAR(2) NOT NULL,
    NO_UF      VARCHAR(40) NOT NULL,
    ID_REGIAO  SMALLINT NOT NULL,
    CONSTRAINT FK21_IBGE_TB03_IBGE_TB02 FOREIGN KEY (ID_REGIAO)
        REFERENCES IBGE_TB02_REGIAO (ID_REGIAO)
);

-- 04 · localidades/mesorregioes.json
CREATE TABLE IBGE_TB04_MESORREGIAO (
    ID_MESORREGIAO  INTEGER PRIMARY KEY,
    NO_MESORREGIAO  VARCHAR(80) NOT NULL,
    ID_UF           SMALLINT NOT NULL,
    CONSTRAINT FK22_IBGE_TB04_IBGE_TB03 FOREIGN KEY (ID_UF)
        REFERENCES IBGE_TB03_UF (ID_UF)
);

-- 05 · localidades/microrregioes.json
CREATE TABLE IBGE_TB05_MICRORREGIAO (
    ID_MICRORREGIAO  INTEGER PRIMARY KEY,
    NO_MICRORREGIAO  VARCHAR(80) NOT NULL,
    ID_MESORREGIAO   INTEGER NOT NULL,
    CONSTRAINT FK23_IBGE_TB05_IBGE_TB04 FOREIGN KEY (ID_MESORREGIAO)
        REFERENCES IBGE_TB04_MESORREGIAO (ID_MESORREGIAO)
);

-- 06 · regionalização "imediata/intermediária" embutida em municipios.json/distritos.json
CREATE TABLE IBGE_TB06_REGIAO_INTERMEDIARIA (
    ID_REGIAO_INTERMEDIARIA  INTEGER PRIMARY KEY,
    NO_REGIAO_INTERMEDIARIA  VARCHAR(80) NOT NULL,
    ID_UF                    SMALLINT NOT NULL,
    CONSTRAINT FK24_IBGE_TB06_IBGE_TB03 FOREIGN KEY (ID_UF)
        REFERENCES IBGE_TB03_UF (ID_UF)
);

-- 07
CREATE TABLE IBGE_TB07_REGIAO_IMEDIATA (
    ID_REGIAO_IMEDIATA       INTEGER PRIMARY KEY,
    NO_REGIAO_IMEDIATA       VARCHAR(80) NOT NULL,
    ID_REGIAO_INTERMEDIARIA  INTEGER NOT NULL,
    CONSTRAINT FK25_IBGE_TB07_IBGE_TB06 FOREIGN KEY (ID_REGIAO_INTERMEDIARIA)
        REFERENCES IBGE_TB06_REGIAO_INTERMEDIARIA (ID_REGIAO_INTERMEDIARIA)
);

-- 08 · localidades/municipios.json
CREATE TABLE IBGE_TB08_MUNICIPIO (
    ID_MUNICIPIO        INTEGER PRIMARY KEY,
    NO_MUNICIPIO        VARCHAR(120) NOT NULL,
    ID_MICRORREGIAO     INTEGER,  -- 1 município (MT) sem microrregião na classificação do IBGE
    ID_REGIAO_IMEDIATA  INTEGER,
    CONSTRAINT FK26_IBGE_TB08_IBGE_TB05 FOREIGN KEY (ID_MICRORREGIAO)
        REFERENCES IBGE_TB05_MICRORREGIAO (ID_MICRORREGIAO),
    CONSTRAINT FK27_IBGE_TB08_IBGE_TB07 FOREIGN KEY (ID_REGIAO_IMEDIATA)
        REFERENCES IBGE_TB07_REGIAO_IMEDIATA (ID_REGIAO_IMEDIATA)
);

CREATE INDEX IX09_IBGE_TB08_ID_MICRORREGIAO ON IBGE_TB08_MUNICIPIO (ID_MICRORREGIAO);

-- 09 · localidades/distritos.json
CREATE TABLE IBGE_TB09_DISTRITO (
    ID_DISTRITO         BIGINT PRIMARY KEY,
    NO_DISTRITO         VARCHAR(120) NOT NULL,
    ID_MUNICIPIO        INTEGER NOT NULL,
    ID_REGIAO_IMEDIATA  INTEGER,
    CONSTRAINT FK28_IBGE_TB09_IBGE_TB08 FOREIGN KEY (ID_MUNICIPIO)
        REFERENCES IBGE_TB08_MUNICIPIO (ID_MUNICIPIO),
    CONSTRAINT FK29_IBGE_TB09_IBGE_TB07 FOREIGN KEY (ID_REGIAO_IMEDIATA)
        REFERENCES IBGE_TB07_REGIAO_IMEDIATA (ID_REGIAO_IMEDIATA)
);

CREATE INDEX IX10_IBGE_TB09_ID_MUNICIPIO    ON IBGE_TB09_DISTRITO (ID_MUNICIPIO);

-- 10 · localidades/subdistritos.json
CREATE TABLE IBGE_TB10_SUBDISTRITO (
    ID_SUBDISTRITO  BIGINT PRIMARY KEY,
    NO_SUBDISTRITO  VARCHAR(120) NOT NULL,
    ID_DISTRITO     BIGINT NOT NULL,
    CONSTRAINT FK30_IBGE_TB10_IBGE_TB09 FOREIGN KEY (ID_DISTRITO)
        REFERENCES IBGE_TB09_DISTRITO (ID_DISTRITO)
);

RESET search_path;
