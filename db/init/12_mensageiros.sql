-- ===================================================================================================================
-- Demais mensageiros (Telegram, Signal, Instagram, ...)
--
-- Tabelas: MSG_TB01_CONTATOS, MSG_TB02_CONVERSAS, MSG_TB03_PARTICIPANTES, MSG_TB04_MENSAGENS,
--          MSG_TB05_ANEXOS
-- ===================================================================================================================

-- PUBLIC no fim do search_path: e onde ficam pg_trgm, fuzzystrmatch e pgcrypto —
-- sem ele, gin_trgm_ops e crypt()/gen_salt() nao sao encontrados sem qualificar.
SET search_path TO INVESTIGACAO, PUBLIC;

-- 01 · contato/participante de um mensageiro (chave natural: extração + app + identificador)
CREATE TABLE MSG_TB01_CONTATOS (
    ID_CONTATO              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_EXTRACAO             BIGINT NOT NULL,
    TP_APP                  TEXT NOT NULL,  -- Instagram | Telegram | Facebook | Discord | ...
    NU_IDENTIFICADOR        TEXT NOT NULL,  -- Identifier do Party (username/id/jid)
    NO_CONTATO              TEXT,
    IN_DONO_DISPOSITIVO     BOOLEAN,
    ID_PESSOA_ASSOCIADA     BIGINT,  -- associação manual (mesma ideia de WPP/SMS)
    ID_MUNICIPIO_ASSOCIADO  INTEGER,
    ID_UF_ASSOCIADA         SMALLINT,
    ID_USUARIO_ASSOCIOU     BIGINT,
    CONSTRAINT FK124_MSG_TB01_INQ_TB02 FOREIGN KEY (ID_EXTRACAO)
        REFERENCES INQ_TB02_EXTRACOES (ID_EXTRACAO),
    CONSTRAINT FK125_MSG_TB01_PES_TB01 FOREIGN KEY (ID_PESSOA_ASSOCIADA)
        REFERENCES DADOS_EXTRAIDOS.PES_TB01_PESSOAS (ID_PESSOA),
    CONSTRAINT FK126_MSG_TB01_IBGE_TB08 FOREIGN KEY (ID_MUNICIPIO_ASSOCIADO)
        REFERENCES DADOS_REFERENCIA.IBGE_TB08_MUNICIPIO (ID_MUNICIPIO),
    CONSTRAINT FK127_MSG_TB01_IBGE_TB03 FOREIGN KEY (ID_UF_ASSOCIADA)
        REFERENCES DADOS_REFERENCIA.IBGE_TB03_UF (ID_UF),
    CONSTRAINT FK128_MSG_TB01_USR_TB01 FOREIGN KEY (ID_USUARIO_ASSOCIOU)
        REFERENCES SEGURANCA.USR_TB01_USUARIOS (ID_USUARIO),
    CONSTRAINT UQ07_MSG_TB01_EXTRACAO_APP_ID UNIQUE (ID_EXTRACAO, TP_APP, NU_IDENTIFICADOR)
);

CREATE INDEX IX61_MSG_TB01_EXTRACAO_APP ON MSG_TB01_CONTATOS (ID_EXTRACAO, TP_APP);

-- 02 · conversa (chat) de um mensageiro
CREATE TABLE MSG_TB02_CONVERSAS (
    ID_CONVERSA          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_EXTRACAO          BIGINT NOT NULL,
    TP_APP               TEXT NOT NULL,
    NU_CHAT_ID           TEXT,
    NO_GRUPO             TEXT,
    TP_CONVERSA          VARCHAR(20) NOT NULL,  -- individual | grupo
    DT_INICIO            TIMESTAMP,
    DT_ULTIMA_ATIVIDADE  TIMESTAMP,
    CD_STATUS_UFDR       VARCHAR(50),
    TP_CHAT_UFDR         VARCHAR(50),
    TX_DESCRICAO         TEXT,
    NO_CONTA             VARCHAR(3000),
    TX_STATUS_CHAT       VARCHAR(3000),
    CONSTRAINT FK129_MSG_TB02_INQ_TB02 FOREIGN KEY (ID_EXTRACAO)
        REFERENCES INQ_TB02_EXTRACOES (ID_EXTRACAO)
);

CREATE INDEX IX58_MSG_TB02_EXTRACAO_APP ON MSG_TB02_CONVERSAS (ID_EXTRACAO, TP_APP);

-- 03 · participantes da conversa
CREATE TABLE MSG_TB03_PARTICIPANTES (
    ID_CONVERSA  BIGINT NOT NULL,
    ID_CONTATO   BIGINT NOT NULL,
    PRIMARY KEY (ID_CONVERSA, ID_CONTATO),
    CONSTRAINT FK130_MSG_TB03_MSG_TB02 FOREIGN KEY (ID_CONVERSA)
        REFERENCES MSG_TB02_CONVERSAS (ID_CONVERSA),
    CONSTRAINT FK131_MSG_TB03_MSG_TB01 FOREIGN KEY (ID_CONTATO)
        REFERENCES MSG_TB01_CONTATOS (ID_CONTATO)
);

CREATE INDEX IF NOT EXISTS IX152_MSG_TB03_ID_CONTATO ON MSG_TB03_PARTICIPANTES (ID_CONTATO);

-- 04 · mensagens
CREATE TABLE MSG_TB04_MENSAGENS (
    ID_MENSAGEM                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CONVERSA                BIGINT NOT NULL,
    ID_CONTATO_REMETENTE       BIGINT,
    TX_MENSAGEM                TEXT,
    DT_MENSAGEM                TIMESTAMP,
    TP_MENSAGEM                VARCHAR(30),
    CD_STATUS_MENSAGEM         VARCHAR(20),
    NO_PASTA                   VARCHAR(20),
    IN_ENVIADA                 BOOLEAN,
    NU_IDENTIFICADOR_ORIGINAL  TEXT,
    VL_LATITUDE                NUMERIC(10,6),
    VL_LONGITUDE               NUMERIC(10,6),
    CD_STATUS_UFDR             VARCHAR(50),
    IN_ENCAMINHADA             BOOLEAN,
    IN_APAGADA_REMETENTE       BOOLEAN,
    IN_TEMPORARIA              BOOLEAN,
    IN_EDITADA                 BOOLEAN,
    TX_ROTULOS                 VARCHAR(3000),
    NU_IDENT_CITADO            VARCHAR(3000),
    TX_DESTINATARIOS           TEXT,
    TX_ASSUNTO                 TEXT,
    TX_MOTIVO_EXCLUSAO         VARCHAR(3000),
    NU_SMSC                    VARCHAR(3000),
    DT_ENTREGUE                TIMESTAMP,
    DT_LIDA                    TIMESTAMP,
    DT_REPRODUZIDA             TIMESTAMP,
    CONSTRAINT FK132_MSG_TB04_MSG_TB02 FOREIGN KEY (ID_CONVERSA)
        REFERENCES MSG_TB02_CONVERSAS (ID_CONVERSA),
    CONSTRAINT FK133_MSG_TB04_MSG_TB01 FOREIGN KEY (ID_CONTATO_REMETENTE)
        REFERENCES MSG_TB01_CONTATOS (ID_CONTATO)
);

CREATE INDEX IX59_MSG_TB04_ID_CONVERSA  ON MSG_TB04_MENSAGENS (ID_CONVERSA);
CREATE INDEX IX60_MSG_TB04_DT_MENSAGEM  ON MSG_TB04_MENSAGENS (DT_MENSAGEM);
CREATE INDEX IX64_MSG_TB04_CONVERSA_MSG ON MSG_TB04_MENSAGENS (ID_CONVERSA, ID_MENSAGEM);
CREATE INDEX IF NOT EXISTS IX148_MSG_TB04_CONTATO_REMETENTE ON MSG_TB04_MENSAGENS (ID_CONTATO_REMETENTE);
CREATE INDEX IF NOT EXISTS IX149_MSG_TB04_APAGADA ON MSG_TB04_MENSAGENS (ID_CONVERSA)
    WHERE CD_STATUS_UFDR IS NOT NULL AND CD_STATUS_UFDR <> 'Intact';
CREATE INDEX IF NOT EXISTS IX188_MSG_TB04_TX_MENSAGEM_TRGM
    ON MSG_TB04_MENSAGENS USING gin (TX_MENSAGEM gin_trgm_ops);
CREATE INDEX IF NOT EXISTS IX207_MSG_TB04_IDENT_ORIGINAL
    ON MSG_TB04_MENSAGENS (NU_IDENTIFICADOR_ORIGINAL)
    WHERE NU_IDENTIFICADOR_ORIGINAL IS NOT NULL;

-- 05 · anexos (mesmo esquema de WPP_TB05, com transcrição de áudio e caminho no zip)
CREATE TABLE MSG_TB05_ANEXOS (
    ID_ANEXO         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_MENSAGEM      BIGINT NOT NULL,
    NO_ARQUIVO       TEXT,
    TP_CONTEUDO      TEXT,
    QT_BYTES         BIGINT,
    CO_CAMINHO_ZIP   TEXT,
    TX_TRANSCRICAO   TEXT,
    TX_TITULO        TEXT,
    CO_URL_ORIGINAL  TEXT,
    CO_FILE_ID       VARCHAR(80),
    CONSTRAINT FK134_MSG_TB05_MSG_TB04 FOREIGN KEY (ID_MENSAGEM)
        REFERENCES MSG_TB04_MENSAGENS (ID_MENSAGEM)
);

CREATE INDEX IX67_MSG_TB05_ID_MENSAGEM ON MSG_TB05_ANEXOS (ID_MENSAGEM);
CREATE INDEX IX81_MSG_TB05_CAMINHO_ZIP ON MSG_TB05_ANEXOS (CO_CAMINHO_ZIP);
CREATE INDEX IF NOT EXISTS IX155_MSG_TB05_FILE_ID ON MSG_TB05_ANEXOS (CO_FILE_ID) WHERE CO_FILE_ID IS NOT NULL;
CREATE INDEX IF NOT EXISTS IX191_MSG_TB05_TX_TRANSCRICAO_TRGM
    ON MSG_TB05_ANEXOS USING gin (TX_TRANSCRICAO gin_trgm_ops);

RESET search_path;
