-- =====================================================================
-- Importação de DADOS_EXTRAIDOS (TSE) — 2014/2016/2018/2020/2022/2024
-- Rodar dentro do container, ex.:
--   docker compose exec -T postgres psql -U $POSTGRES_USER -d $POSTGRES_DB \
--       -f /db/import/05_import_tse.sql
-- Pressupõe db/data montado em /db (ver docker-compose.yml, volume ./db:/db:ro)
--
-- O layout de colunas do TSE mudou ao longo dos anos (candidatos_2016 tem
-- 75 colunas contra 50 nos demais anos; votacao_candidato_munzona_2014 tem
-- 38 contra 50; votacao_partido_munzona varia entre 28/36/38 colunas).
-- Por isso cada formato distinto ganha sua própria staging table (texto
-- puro — COPY nunca falha por tipo/formato), e o INSERT final faz a
-- correspondência de colunas equivalentes entre formatos. Datas usam uma
-- função "safe_date" que devolve NULL em vez de abortar o import por causa
-- de uma data inválida em algum lugar no meio de milhões de linhas.
-- TSE_TB02_PARTIDOS/TSE_TB03_ELEICOES são derivadas (sem arquivo próprio).
-- =====================================================================

SET search_path TO DADOS_EXTRAIDOS;
SET DATESTYLE TO 'ISO, DMY';

CREATE OR REPLACE FUNCTION PG_TEMP.SAFE_DATE(TXT TEXT) RETURNS DATE AS $$
BEGIN
    RETURN TO_DATE(TXT, 'DD/MM/YYYY');
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION PG_TEMP.SAFE_INT(TXT TEXT) RETURNS INTEGER AS $$
BEGIN
    RETURN TXT::INTEGER;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION PG_TEMP.SAFE_BIGINT(TXT TEXT) RETURNS BIGINT AS $$
BEGIN
    RETURN TXT::BIGINT;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION PG_TEMP.SAFE_SMALLINT(TXT TEXT) RETURNS SMALLINT AS $$
BEGIN
    RETURN TXT::SMALLINT;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

