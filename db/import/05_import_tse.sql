    PG_TEMP.SAFE_INT(CD_ELEICAO), PG_TEMP.SAFE_SMALLINT(ANO_ELEICAO), PG_TEMP.SAFE_SMALLINT(CD_TIPO_ELEICAO),
    NM_TIPO_ELEICAO, DS_ELEICAO, PG_TEMP.SAFE_DATE(DT_ELEICAO), TP_ABRANGENCIA
