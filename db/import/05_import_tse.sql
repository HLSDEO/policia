-- 4) TSE_TB02_PARTIDOS / TSE_TB03_ELEICOES — derivadas (distinct)
-- =====================================================================
INSERT INTO TSE_TB02_PARTIDOS (NR_PARTIDO, SG_PARTIDO, NO_PARTIDO)
SELECT DISTINCT ON (PG_TEMP.SAFE_SMALLINT(NR_PARTIDO)) PG_TEMP.SAFE_SMALLINT(NR_PARTIDO), SG_PARTIDO, NM_PARTIDO
FROM (
    SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_CAND_A
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_CAND_B
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_VOTCAND_A
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_VOTCAND_B
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_VOTPART_A
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_VOTPART_B
    UNION ALL SELECT NR_PARTIDO, SG_PARTIDO, NM_PARTIDO FROM STG_VOTPART_C
) x
WHERE PG_TEMP.SAFE_SMALLINT(NR_PARTIDO) IS NOT NULL
ON CONFLICT (NR_PARTIDO) DO NOTHING;

INSERT INTO TSE_TB03_ELEICOES (CD_ELEICAO, NU_ANO_ELEICAO, CD_TIPO_ELEICAO, NO_TIPO_ELEICAO, DS_ELEICAO, DT_ELEICAO, TP_ABRANGENCIA)
