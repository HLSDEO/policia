-- Eventos com data extraídos do texto dos documentos de um Caso — a linha do tempo do caso
-- (tela caso_timeline.html). Determinístico por regex, sem IA (funcoes/achados_texto.py
-- extrair_datas_de_texto). Correspondente declarativo em db/init/23_casos.sql
-- (CREATE TABLE CAS_TB12_EVENTOS + índices IX247/IX248).
CREATE TABLE INVESTIGACAO.CAS_TB12_EVENTOS (
    ID_EVENTO       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CASO         BIGINT NOT NULL,
    ID_DOCUMENTO    BIGINT NOT NULL,
    DT_EVENTO       DATE NOT NULL,
    TX_CONTEXTO     TEXT,
    QT_OCORRENCIAS  INTEGER NOT NULL DEFAULT 1,
    IN_AUTOMATICO   BOOLEAN NOT NULL DEFAULT true,
    DT_CRIACAO      TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT FK256_CAS_TB12_CAS_TB01 FOREIGN KEY (ID_CASO)
        REFERENCES INVESTIGACAO.CAS_TB01_CASOS (ID_CASO),
    CONSTRAINT FK257_CAS_TB12_CAS_TB02 FOREIGN KEY (ID_DOCUMENTO)
        REFERENCES INVESTIGACAO.CAS_TB02_DOCUMENTOS (ID_DOCUMENTO)
);

CREATE INDEX IX247_CAS_TB12_ID_CASO ON INVESTIGACAO.CAS_TB12_EVENTOS (ID_CASO, DT_EVENTO);
CREATE INDEX IX248_CAS_TB12_ID_DOCUMENTO ON INVESTIGACAO.CAS_TB12_EVENTOS (ID_DOCUMENTO);
