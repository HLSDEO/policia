-- Unifica "caso" dentro do inquerito: caso de inteligencia passa a ser um inquerito com a
-- flag IN_CASO_INTELIGENCIA (importado pelas mesmas fontes: UFDR, RIF, SIMBA, IPED, documento).
-- O subsistema antigo de casos (CAS_TB01..CAS_TB12) e removido; os dados de caso sao descartados
-- de proposito, conforme autorizado.

SET search_path TO INVESTIGACAO, PUBLIC;

-- Flag no inquerito: quando true, e um caso de inteligencia (sem numero de ePol — o NU_INQUERITO
-- recebe um numero gerado automaticamente "CASO-AAAA.NNNN").
ALTER TABLE INQ_TB01_INQUERITOS
    ADD COLUMN IN_CASO_INTELIGENCIA BOOLEAN NOT NULL DEFAULT false;

-- Indice parcial para as listagens filtrarem/contarem casos de inteligencia
CREATE INDEX IF NOT EXISTS IX402_INQ_TB01_CASO_INTELIGENCIA
    ON INQ_TB01_INQUERITOS (IN_CASO_INTELIGENCIA) WHERE IN_CASO_INTELIGENCIA;

-- Remocao do subsistema antigo de casos, em ordem de FK (filhas antes da mae).
-- IA_TB04_AUDITORIA e IA_TB05_RELATORIOS_DOCX guardavam ID_CASO para as origens de caso;
-- a coluna e as FKs saem junto (dados antigos de caso descartados de proposito).
ALTER TABLE IA_TB05_RELATORIOS_DOCX DROP CONSTRAINT IF EXISTS CK09_IA_TB05_DONO;
ALTER TABLE IA_TB05_RELATORIOS_DOCX DROP CONSTRAINT IF EXISTS FK244_IA_TB05_CAS_TB01;
ALTER TABLE IA_TB05_RELATORIOS_DOCX DROP COLUMN IF EXISTS ID_CASO;
ALTER TABLE IA_TB04_AUDITORIA DROP CONSTRAINT IF EXISTS FK136_IA_TB04_CAS_TB01;
ALTER TABLE IA_TB04_AUDITORIA DROP COLUMN IF EXISTS ID_CASO;

DROP TABLE IF EXISTS CAS_TB10_PERMISSOES;
DROP TABLE IF EXISTS CAS_TB12_EVENTOS;
DROP TABLE IF EXISTS CAS_TB11_ACHADOS;
DROP TABLE IF EXISTS CAS_TB09_RESOLUCOES_IDENTIFICACOES;
DROP TABLE IF EXISTS CAS_TB08_PROCESSAMENTOS_IA;
DROP TABLE IF EXISTS CAS_TB07_MENSAGENS_IA;
DROP TABLE IF EXISTS CAS_TB06_CONVERSAS_IA;
DROP TABLE IF EXISTS CAS_TB05_BUSCAS;
DROP TABLE IF EXISTS CAS_TB04_RELACOES;
DROP TABLE IF EXISTS CAS_TB03_ENTIDADES;
DROP TABLE IF EXISTS CAS_TB02_DOCUMENTOS;
DROP TABLE IF EXISTS CAS_TB01_CASOS;

RESET search_path;
