-- Camadas geoespaciais importadas de shapefile (.shp) e desenhadas sobre o mapa da aba "Grafo"
-- das localizações, com filtro "só o que está dentro desta área".
--
-- Correspondente declarativo em db/init/15_localizacao.sql (as três tabelas GEO_TB02/03/04).
-- Sem PostGIS: a contenção usa o tipo POLYGON nativo do Postgres (`polígono @> ponto`).

CREATE TABLE IF NOT EXISTS INVESTIGACAO.GEO_TB02_CAMADAS (
    ID_CAMADA         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_INQUERITO      BIGINT NOT NULL,
    NO_CAMADA         VARCHAR(200) NOT NULL,
    NO_ARQUIVO        VARCHAR(300),
    CO_HASH           CHAR(64),
    NO_PROJECAO       VARCHAR(200),
    TX_PROJECAO       TEXT,
    QT_FEICOES        INTEGER NOT NULL DEFAULT 0,
    QT_VERTICES       INTEGER NOT NULL DEFAULT 0,
    VL_TOLERANCIA     NUMERIC(12,8),
    VL_LAT_MIN        NUMERIC(10,6),
    VL_LAT_MAX        NUMERIC(10,6),
    VL_LON_MIN        NUMERIC(10,6),
    VL_LON_MAX        NUMERIC(10,6),
    CO_COR            VARCHAR(9) NOT NULL DEFAULT '#f59e0b',
    DT_IMPORTACAO     TIMESTAMP NOT NULL DEFAULT now(),
    NO_IMPORTADA_POR  VARCHAR(200),
    CONSTRAINT FK250_GEO_TB02_INQ_TB01 FOREIGN KEY (ID_INQUERITO)
        REFERENCES INVESTIGACAO.INQ_TB01_INQUERITOS (ID_INQUERITO)
);

CREATE INDEX IF NOT EXISTS IX240_GEO_TB02_INQUERITO
    ON INVESTIGACAO.GEO_TB02_CAMADAS (ID_INQUERITO, DT_IMPORTACAO DESC);

CREATE TABLE IF NOT EXISTS INVESTIGACAO.GEO_TB03_FEICOES (
    ID_FEICAO     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_CAMADA     BIGINT NOT NULL,
    NU_ORDEM      INTEGER NOT NULL,
    NO_FEICAO     TEXT,
    TX_ATRIBUTOS  JSONB,
    TX_GEOMETRIA  JSONB NOT NULL,
    VL_LAT_MIN    NUMERIC(10,6) NOT NULL,
    VL_LAT_MAX    NUMERIC(10,6) NOT NULL,
    VL_LON_MIN    NUMERIC(10,6) NOT NULL,
    VL_LON_MAX    NUMERIC(10,6) NOT NULL,
    CONSTRAINT FK251_GEO_TB03_GEO_TB02 FOREIGN KEY (ID_CAMADA)
        REFERENCES INVESTIGACAO.GEO_TB02_CAMADAS (ID_CAMADA) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IX241_GEO_TB03_CAMADA
    ON INVESTIGACAO.GEO_TB03_FEICOES (ID_CAMADA, NU_ORDEM);

CREATE TABLE IF NOT EXISTS INVESTIGACAO.GEO_TB04_ANEIS (
    ID_ANEL     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_FEICAO   BIGINT NOT NULL,
    ID_CAMADA   BIGINT NOT NULL,
    IN_BURACO   BOOLEAN NOT NULL DEFAULT false,
    VL_LAT_MIN  NUMERIC(10,6) NOT NULL,
    VL_LAT_MAX  NUMERIC(10,6) NOT NULL,
    VL_LON_MIN  NUMERIC(10,6) NOT NULL,
    VL_LON_MAX  NUMERIC(10,6) NOT NULL,
    PG_ANEL     POLYGON NOT NULL,
    CONSTRAINT FK252_GEO_TB04_GEO_TB03 FOREIGN KEY (ID_FEICAO)
        REFERENCES INVESTIGACAO.GEO_TB03_FEICOES (ID_FEICAO) ON DELETE CASCADE,
    CONSTRAINT FK253_GEO_TB04_GEO_TB02 FOREIGN KEY (ID_CAMADA)
        REFERENCES INVESTIGACAO.GEO_TB02_CAMADAS (ID_CAMADA) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IX242_GEO_TB04_CAMADA
    ON INVESTIGACAO.GEO_TB04_ANEIS (ID_CAMADA, VL_LAT_MIN, VL_LAT_MAX);
CREATE INDEX IF NOT EXISTS IX243_GEO_TB04_FEICAO
    ON INVESTIGACAO.GEO_TB04_ANEIS (ID_FEICAO);
